const translateSeedMetadata = (value, { preserveUnknown = false } = {}) => {
  const source = String(value || "").trim();
  if (!source) return "";

  if (metadataTranslations.has(source)) return metadataTranslations.get(source);
  if (productionTitleTranslations.has(source)) return productionTitleTranslations.get(source);
  if (source === "Madlenianum" || source === "Instagram") return source;

  const eventDate = source.match(/^(\d{2})\.авг$/u);
  if (eventDate) return `${eventDate[1]} Aug`;

  const numberedTitle = source.match(/^(.*?)(?:\s+(gallery|main))?\s+(\d+)$/i);
  if (numberedTitle) {
    const title = translatedProductionTitle(numberedTitle[1]);
    const qualifier = numberedTitle[2] ? ` ${numberedTitle[2].toLowerCase()}` : "";
    return `${title}${qualifier} ${numberedTitle[3]}`;
  }

  const qualifiedTitle = source.match(/^(.*?)(?:\s+(gallery|main))$/i);
  if (qualifiedTitle) {
    return `${translatedProductionTitle(qualifiedTitle[1])} ${qualifiedTitle[2].toLowerCase()}`;
  }

  if (source.startsWith("Scena iz predstave ")) {
    return `Scene from ${translatedProductionTitle(source.slice("Scena iz predstave ".length))}`;
  }
  if (source.startsWith("Plakat predstave ")) {
    return `Poster for ${translatedProductionTitle(source.slice("Plakat predstave ".length))}`;
  }
  if (source.endsWith(" - plakat")) {
    return `${translatedProductionTitle(source.slice(0, -" - plakat".length))} - poster`;
  }

  return preserveUnknown ? transliterateSerbian(source) : "";
};

