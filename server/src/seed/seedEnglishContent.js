const transliterateSerbian = (value = "") => String(value)
  .replace(/Đ/g, "Dj")
  .replace(/đ/g, "dj")
  .replace(/[ČĆ]/g, "C")
  .replace(/[čć]/g, "c")
  .replace(/Š/g, "S")
  .replace(/š/g, "s")
  .replace(/Ž/g, "Z")
  .replace(/ž/g, "z");

